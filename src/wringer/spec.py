def read_prd(path: Path, root: Path, redactor: Redactor | None = None) -> str:
    """The PRD's text, bounded, confined to the repo, and scrubbed.

    Its bytes travel to an endpoint, so it gets the rubric's rules: inside the
    repository, under a declared ceiling.

    **Scrubbed here, at the read**, not on the way to disk. Scrubbing only the
    artifact would produce a `request.json` saying `[REDACTED]` beside a socket
    that carried the real value — an audit record that denies what actually
    left the machine, which is worse than no audit record at all. Everything
    downstream (the request, the quoted `intent`, the briefs) is built from
    this one scrubbed string, so all of them agree.
    """
    try:
        resolved = path.resolve()
        inside = resolved.is_relative_to(root.resolve())
    except OSError as exc:  # pragma: no cover - unreadable path
        raise SpecError(f"cannot read {path}: {exc}") from exc
    if not inside:
        raise SpecError(
            f"PRD {path} resolves outside the repository ({resolved}) — its "
            "contents would be sent to an endpoint, so it must be a file the "
            "repo itself holds"
        )
    if not resolved.is_file():
        raise SpecError(f"no PRD at {path}")

    raw = resolved.read_bytes()
    if len(raw) > MAX_PRD_BYTES:
        raise SpecError(
            f"PRD {path} is {len(raw)} bytes, over the {MAX_PRD_BYTES}-byte "
            "limit — these bytes travel"
        )
    text = raw.decode("utf-8", errors="replace").strip()
    if not text:
        raise SpecError(f"PRD {path} is empty — there is nothing to draft from")
    return (redactor or Redactor()).scrub(text)


def quote_intent(prd: str) -> str:
    """The human's own words, verbatim, for the artifact they will approve.

    Never the model's summary of them. If a drafter misread the PRD, the
    reader needs the PRD beside the criteria to notice.
    """
    # Control characters YAML cannot carry in a block scalar. A PRD holding
    # one would otherwise produce a spec file that will not load — and the
    # first thing anyone would do with it is approve it.
    quoted = "".join(
        ch for ch in prd if ch in "\t\n" or (ch >= " " and ch != "\x7f")
    )
    if len(quoted) <= MAX_INTENT_CHARS:
        return quoted
    return (
        quoted[:MAX_INTENT_CHARS]
        + f"\n\n[wringer: quoted the first {MAX_INTENT_CHARS} characters of "
        "the PRD; read the file itself for the rest]"
    )


# How many repository paths the request may carry. A listing is context a
# drafter pays for by the token, and an unbounded one would push a large
# repository's PRD out of the window entirely. 400 is a number, not a
# measurement: it fits every repository this programme has driven, and the
# truncation is announced rather than silent, which is the part that matters.
MAX_LISTED_FILES = 400


def repository_files(root: Path) -> tuple[str, ...]:
    """The repository's TRACKED files, as repo-relative paths.

    **Tracked, from git, never a filesystem walk.** A walk offers the drafter
    `.venv/lib/.../test_foo.py` and `node_modules/...`, and a binding naming
    one of those is a check that exists on exactly one machine. What is
    committed is what everybody has.

    Where git cannot answer — no repository, no git, a repository with no
    commits — this returns nothing. That is the honest failure: the request
    goes out without a listing, rule 6 has nothing to point at, and the
    drafter proposes no binding, which is precisely the behaviour that shipped
    before this existed. A stop here would refuse a repo for a fact that is
    merely unavailable.
    """
    import subprocess

    try:
        done = subprocess.run(
            ["git", "ls-files", "-z"],
            cwd=root, capture_output=True, check=False, timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return ()
    if done.returncode != 0:
        return ()
    from wringer import git

    names = git.decode(done.stdout).split("\0")
    return tuple(sorted(name for name in names if name))


def render_request(
    prd: str,
    model: str,
    max_output_tokens: int,
    declared: tuple[config.Gate, ...] = (),
    files: tuple[str, ...] = (),
) -> dict:
    """The exact chat-completions body.

    Built from the PRD and, if the repo has any, the gate commands it already
    declares — shown so the drafter can propose *those* rather than guess at a
    build system it cannot see. A drafter shown nothing invents; law 5 is why
    the proposals are a diff a human applies, and this is how to need that
    safety net less often.

    **`files` is the repository's own tracked paths, and rule 6 is
    unsatisfiable without it.** Rule 6 has always told the drafter that every
    file a binding names must already exist; until 2026-08-19 the request
    never said which files those were. Driven against a real PRD,
    `claude-opus-5` did the correct thing with that — it proposed no binding at
    all and raised an open question asking what the repository contains — so
    every criterion came back `unbound`, no worker turn ran, and nothing was
    proved. The rule was right and the input was missing.

    Paths only. No contents: a file listing is cheap and says what EXISTS,
    which is the fact rule 6 needs; shipping the sources would be a different
    and much larger claim about what the drafter is being asked to do.
    """
    known = "\n".join(f"- {g.id}: {g.run}" for g in declared)
    shown = tuple(files)[:MAX_LISTED_FILES]
    listing = "\n".join(f"- {name}" for name in shown)
    if len(files) > len(shown):
        listing += (
            f"\n[{len(files) - len(shown)} more paths are not listed — this is "
            "not the whole repository, so a file you need may be missing from "
            "it]"
        )
    user = (
        "# Product requirements\n\n"
        f"{prd}\n\n"
        "---\n\n"
        + (
            f"## Gates this repository already declares\n{known}\n\n"
            "Propose only gates that are missing, and phrase them the way "
            "these are.\n\n"
            if known
            else ""
        )
        + (
            f"## Files this repository contains\n{listing}\n\n"
            "These are its tracked files. A `gate_bindings` command may name "
            "ONLY a path from this list; anything else does not exist here.\n\n"
            if listing
            else ""
        )
        + "## Your task\n"
        "Turn the requirements above into a build specification.\n\n"
        "Rules, in order of importance:\n"
        "1. **AT MOST THREE QUESTIONS, and a person who has never seen this "
        "code must be able to answer every one of them.** The reader is a "
        "product manager. Ask only what you genuinely cannot determine and "
        "only a person can decide.\n"
        "   - **Never ask what you can look up.** If the answer is in a file "
        "in this repository, you do not know it yet — say so in the "
        "criterion, do not ask.\n"
        "   - **Never ask about testing machinery**: which runner executes "
        "what, whether a check is wired into a command, whether new test "
        "files may be written. Those are not theirs to decide.\n"
        "   - **Everything else you would have asked, DECIDE** — pick the "
        "most obvious behaviour — and put the decision in the `assumptions` "
        "list below, NOT in a criterion's guidance. A visible assumption they "
        "approve is worth more than a question they cannot answer, but only "
        "if it is somewhere they will read it as a decision. Guidance is "
        "instructions for checking the work; a person approving a plan does "
        "not read it, so a decision written there is a decision hidden. Every "
        "assumption carries the question it displaced, so they can ask it "
        "after all.\n"
        "2. **Every criterion must be checkable.** Prefer criteria a test or "
        "a lint can decide. Mark a criterion `\"human\": true` when only a "
        "person can judge it — taste, tone, or a trade-off.\n"
        "3. **Propose gates the repository could actually run** — its own "
        "test and lint commands. Propose none rather than inventing one.\n"
        "4. Split the work into tasks a single agent can finish. Give each "
        "TWO things: an `objective` — one paragraph of instructions for the "
        "engineer — and an `outcome`, ONE PLAIN SENTENCE saying what the "
        "person who asked for this will be able to DO once it is done. The "
        "outcome is what they read on the plan they approve; write it in "
        "their words, not in yours.\n"
        "5. **For each criterion a machine can decide, propose a "
        "`gate_bindings` entry**: a command that FAILS today and passes only "
        "once that criterion is met, and the criterion id it proves. One "
        "criterion, one binding, and never a `human: true` one. **A binding "
        "that already passes is worth nothing** — the criterion is unbuilt, "
        "so a command that is green now is not testing it. Omit any binding "
        "you cannot write that way rather than writing a weak one.\n"
        "6. **A binding must run a check that EXISTS TODAY.** Every file it "
        "names must already be in the repository"
        + (
            " — the listing above is what that means, so choose from it"
            if listing
            else ""
        )
        + ". Do not name a test file "
        "that would have to be written — it would fail because it is absent "
        "rather than because the criterion is unmet, and a check that arrives "
        "with the work cannot evidence the work. If no existing check can "
        "decide a criterion, propose no binding for it and say so in the "
        "criterion's own guidance — not as a question.\n"
        "7. **A binding may not repeat a command that already runs.** If its "
        "`run` is one of the gates listed above, it is refused outright and "
        "the criterion is left with nothing checking it — the check passes "
        "today, so no amount of work can make it fail, and a check that "
        "cannot fail proves nothing. Give it a command of its own or give it "
        "none.\n\n"
        "## Reply format\n"
        "Return ONLY a JSON object, no prose and no code fence:\n"
        "{\n"
        '  "title": "<one line>",\n'
        '  "open_questions": [{"id": "<slug>", "question": "<one line>", '
        '"required": true}],   // AT MOST 3, and each answerable by a '
        'non-technical person\n'
        '  "assumptions": [{"id": "<slug>", "decision": "<one sentence: what '
        'you decided>", "why": "<one sentence: why>", "instead_of_asking": '
        '"<the question you would have asked>", "criteria": ["<ids of the '
        'criteria below whose WORDING this decision shaped>"]}],\n'
        '  "criteria": [{"id": "<slug>", "title": "<one line>", '
        '"guidance": "<how to check it>", "required": true, "human": false}],\n'
        '  "gates": [{"id": "<slug>", "run": "<shell command>"}],\n'
        '  "gate_bindings": [{"id": "<slug>", "run": "<shell command>", '
        '"proves": "<criterion id from above>"}],\n'
        '  "tasks": [{"id": "<slug>", "brief": "briefs/<slug>.md", '
        '"dir": ".", "objective": "<one paragraph, for the engineer>", '
        '"outcome": "<one sentence, for the person who asked>"}]\n'
        "}\n"
        "Slugs are letters, digits, '-' and '_'. At least one criterion must "
        "be `required`. At least one task. `gates` are the repository's "
        "existing checks; `gate_bindings` are the per-criterion acceptance "
        "checks, and only these carry `proves`. An `assumptions` id must not "
        "be the id of a question you are also asking — decide it or ask it, "
        "never both.\n\n"
        "An assumption's `criteria` names every criterion below whose "
        "WORDING depends on that decision. You are the only party that "
        "can know this: you took the decision and then wrote the "
        "criteria. If the person later overrules the decision, those "
        "criteria are worded against something they have rejected, and "
        "a check that passes against wrong wording proves the wrong "
        "thing perfectly. Omit the key only when a decision shaped no "
        "criterion at all."
    )
    # **No `temperature` key, and its absence is the fix rather than an
    # omission.** Until 2026-08-18 this body carried `"temperature": 0`, and
    # every current-generation Anthropic model — Opus 5, Opus 4.8, Opus 4.7,
    # Sonnet 5, Fable 5 — refuses it outright: HTTP 400, *"`temperature` is
    # deprecated for this model"*, before a token is drafted. So a product
    # manager who named the model their team actually uses got an error
    # instead of a spec, which is the whole surface failing at its first step.
    #
    # No config knob replaces it, deliberately. `temperature: 0` never bought
    # determinism here — the drafter's correctness mechanism is
    # parse-or-refuse (`parse_response` puts every proposed field through the
    # same parser the file itself will face), not sampling temperature. A
    # `judge.temperature` key would be surface nobody asked for, and if a real
    # need arrives it can arrive with a use case.
    #
    # `wring judge` is a DIFFERENT request and keeps its `temperature: 0`:
    # `schema/judge-request.schema.json` requires it with `"const": 0`, that
    # schema is frozen (`schema/frozen.json`), and a judge that is not
    # deterministic is not a gate. Nothing here changes it.
    #
    # Old `request.json` files keep their `temperature` and stay readable:
    # nothing reads the key back out, and no schema governs this body.
    return {
        "model": model,
        "max_tokens": max_output_tokens,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You turn product requirements into a build specification: "
                    "acceptance criteria, gates, and tasks. You never invent a "
                    "requirement — anything the document does not say becomes "
                    "an open question. Answer only with the requested JSON."
                ),
            },
            {"role": "user", "content": user},
        ],
    }


def _drop_unknown_reply_keys(drafted: dict) -> tuple[dict, tuple[str, ...]]:
    """R3 (2026-08-18): a DRAFTED reply's decorative key is dropped, with a
    note naming the key, where it sat, and the first line of what it carried.

    One drafting run in four died on 2026-08-18 with `tasks[0]: unknown
    keys: objective_note` — a whole paid-for draft refused over four empty
    strings. The asymmetry is the duplicate-bindings ruling again: a model's
    proposal survives with its losses named in `Draft.notes`; a person's
    `wringer.spec.yaml` keeps the strict error in `parse`/`load`, untouched
    below, because a typo silently dropped is a person's content vanished.

    **The interlock does not become droppable by moving down a level.** A
    reply carrying `approved` on a task, question, criterion OR ASSUMPTION is
    refused whole, exactly as at top level — and `answer` on an open question
    is a KNOWN key, so the self-answer refusal above this has already run.
    """
    sections = (
        ("open_questions", _QUESTION_KEYS),
        ("criteria", _CRITERION_KEYS),
        ("tasks", _TASK_KEYS),
        # **FOUR sections, and the fourth is why this tuple is a list rather
        # than three hand-written blocks.** `assumptions` is a new id-keyed
        # container, so a section this walk did not cover would be a new place
        # to smuggle `approved` — in the one parser whose whole design is that
        # no such place exists.
        ("assumptions", _ASSUMPTION_KEYS),
    )
    notes: list[str] = []
    cleaned = dict(drafted)
    for section, known in sections:
        entries = drafted.get(section)
        if not isinstance(entries, list):
            continue
        rebuilt: list[Any] = []
        for index, entry in enumerate(entries):
            if not isinstance(entry, dict):
                rebuilt.append(entry)
                continue
            unknown = sorted(set(entry) - known)
            if "approved" in unknown:
                raise SpecError(
                    f"the reply carried 'approved' on {section}[{index}] — "
                    "the interlock is not the model's to work, wherever it "
                    "is written. Nothing was written"
                )
            for key in unknown:
                lines = str(entry[key]).strip().splitlines()
                carried = lines[0][:100] if lines else "it carried nothing"
                notes.append(
                    f"dropped from the drafted reply: {section}[{index}] "
                    f"('{entry.get('id', '?')}') carried unknown key "
                    f"'{key}' — {carried}"
                )
            rebuilt.append(
                {k: v for k, v in entry.items() if k in known}
                if unknown else entry
            )
        cleaned[section] = rebuilt
    return cleaned, tuple(notes)


def parse_response(
    body: Any, prd: str, declared: Any = (), files: Any = ()
) -> Draft:
    """Turn a model reply into a validated spec and its proposed gates, or
    refuse the whole reply.

    Every field the model proposes goes through the same parser the file
    itself will face, so the caller either gets a spec that loads or an
    exception — never a half-formed document to write out and apologise for.

    `approved` is not read from the reply. There is no key here that could
    set it.
    """
    try:
        content = body["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError):
        raise SpecError(
            "the reply had no message content — nothing was drafted, and "
            "nothing was written"
        ) from None
    try:
        drafted = json.loads(_strip_fences(str(content)))
    except (ValueError, json.JSONDecodeError) as exc:
        raise SpecError(
            f"the reply was not the JSON object the request asked for ({exc}) "
            "— nothing was written"
        ) from exc
    if not isinstance(drafted, dict):
        raise SpecError("the reply was JSON but not an object — nothing was written")

    # Strict, like every other loader here, and loudest where it matters: a
    # reply carrying `approved` is a reply that tried to work the interlock,
    # and the honest answer to that is a refusal a human reads, not a silent
    # discard.
    unknown = sorted(
        set(drafted)
        - {"title", "open_questions", "criteria", "gates", "tasks",
           "gate_bindings", "assumptions"}
    )
    if unknown:
        raise SpecError(
            f"the reply carried keys the request did not ask for: "
            f"{', '.join(unknown)} — nothing was written"
        )

    asked = drafted.get("open_questions") or []
    if isinstance(asked, list):
        answered = [
            q.get("id") for q in asked
            if isinstance(q, dict) and str(q.get("answer") or "").strip()
        ]
        if answered:
            # The second interlock, and the reply tried to work it. An
            # `answer` written by the drafter is the assumption it was told to
            # ask about, wearing a human's clothes: `wring plan` would let it
            # through and the brief would present it as a decision someone
            # made. Refused for the same reason as `approved`.
            raise SpecError(
                "the reply answered its own open question"
                f"{'s' if len(answered) > 1 else ''} "
                f"({', '.join(str(q) for q in answered)}) — an assumption a "
                "human did not make is exactly what an open question is for. "
                "Nothing was written"
            )

    # BEFORE the drop-walk: `outcome` is not in `_TASK_KEYS` and must not be,
    # so the walk below would eat it with a note.
    drafted, outcomes, outcome_notes = lift_outcomes(drafted)

    drafted, dropped = _drop_unknown_reply_keys(drafted)

    drafted_spec = parse(
        {
            "schema_version": SCHEMA_VERSION,
            # Written here, not read from the reply. The interlock is a
            # constant in this expression; there is no branch that sets it.
            "approved": False,
            "title": drafted.get("title"),
            # The human's words, not the model's paraphrase of them.
            "intent": quote_intent(prd),
            "open_questions": drafted.get("open_questions") or [],
            "criteria": drafted.get("criteria"),
            "gates": drafted.get("gates") or [],
            "tasks": drafted.get("tasks"),
        },
        "the drafted spec",
    )
    # **The question cap, checked HERE and deliberately not earlier.**
    # `drafted_spec.questions` are validated `Question` objects, so `required`
    # is a real bool and every message `_parse_questions` exists to give has
    # already fired. Counting raw dicts before `parse` would have this cap
    # stealing those errors — or crashing on exactly the shapes they refuse.
    #
    # A refused draft is a sub-cent re-roll. A product manager facing nine
    # blocking questions is this surface failing at the thing it is for.
    blocking = sum(1 for question in drafted_spec.questions if question.required)
    if blocking > MAX_REQUIRED_QUESTIONS:
        raise SpecError(
            f"the reply asks {blocking} questions a person must answer before "
            f"anything can be built, and the limit is {MAX_REQUIRED_QUESTIONS}. "
            "The request says so in as many words; a rule the drafter agreed to "
            "and did not keep is why this is a check and not a sentence. "
            "Nothing was written — drafting again costs a fraction of a penny"
        )

    # **A blocking question a PM cannot answer is the product failing at the
    # thing it is for**, and the request already forbids it in as many words.
    unanswerable = unanswerable_questions(drafted_spec.questions, files)
    if unanswerable:
        first = unanswerable[0]
        raise SpecError(
            f"the reply asks a question only somebody who can read the "
            f"repository could answer: {first.question!r} — it names a file "
            "in this project, and every required question must be answerable "
            "by the person who wrote the document. The request says 'never "
            "ask what you can look up', and the file listing it was given is "
            "how it looks it up. Nothing was written — drafting again costs a "
            "fraction of a penny"
        )

    # Checked at draft time, not left for `wring plan`: a spec that reads fine,
    # gets approved, and only then turns out to be unplannable spends the
    # human's attention for nothing.
    validate_rubric_text(render_rubric(drafted_spec))
    # Checked here, before the caller writes anything, and against the
    # criteria from THIS reply: a sidecar validated later would mean a spec on
    # disk whose companion file was refused, and the pair only means anything
    # together.
    #
    # **Both sources of "already runs", and the reply's own block is the one
    # that caught the measured case**: on 2026-08-17 the model listed `test:
    # pytest -q` under `gates` and then proposed the identical command as a
    # binding, in the same breath. `declared` is what `.wringer.yaml` has, which
    # the reply cannot see for itself.
    proposed, notes, already = parse_bindings(
        drafted.get("gate_bindings"),
        drafted_spec.criteria,
        "the drafted gates",
        (*drafted_spec.gates, *declared),
    )
    assumptions, assumption_notes = parse_assumptions(
        drafted.get("assumptions"),
        "the drafted assumptions",
        drafted_spec.questions,
        drafted_spec.criteria,
    )
    return Draft(
        spec=drafted_spec,
        gates=proposed,
        assumptions=assumptions,
        outcomes=outcomes,
        notes=(
            *dropped,
            *notes,
            # Informational, and last: a gate already installed by an earlier
            # run is news the operator may want and is never a problem.
            *already,
            *outcome_notes,
            *assumption_notes,
            *missing_outcome_notes(drafted_spec.tasks, outcomes),
            *buried_decision_notes(drafted_spec.criteria),
        ),
    )


def same_command(one: str, other: str) -> bool:
    """Two `run:` strings that would execute the same thing.

    Whitespace only. Nothing cleverer is attempted and nothing should be:
    `pytest -q` and `python -m pytest -q` run the same suite and this says
    they differ, which is the safe direction — a false NO here costs a
    criterion its binding, a false YES would let a check that cannot
    discriminate stand as proof.
    """
    return " ".join(one.split()) == " ".join(other.split())


def parse_bindings(
    raw: Any,
    criteria: Any,
    where: str,
    declared: Any = (),
) -> tuple[tuple[config.Gate, ...], tuple[str, ...], tuple[str, ...]]:
    """The proposed gates and the ones refused, checked against the criteria
    beside them before a byte of either document is written.

    Every entry goes through `config.parse_gate` with `allow_proves=True`:
    the SAME parser `.wringer.yaml` will face, so Wringer can never propose a
    gate its own loader would reject — the rule the spec's `gates:` block has
    had since P2, extended to the channel that carries bindings.

    The join is then `config.check_bindings`, the shipped rules, not a copy.

    **`declared` is every gate that already runs**, and a binding repeating one
    of them is refused. Measured on 2026-08-17: for the criterion "no
    regression on the report page" the drafter proposed `run: pytest -q` — byte
    for byte the repository's own `test` gate, green before, during and after
    the work. The criterion came back `unevidenced` and the handover was held.
    The request's own rules already said not to (*"A binding that already
    passes is worth nothing"*) and the model did it anyway; prompts are not
    guards.
    """
    if raw is None:
        return (), (), ()
    if not isinstance(raw, list):
        raise SpecError(f"{where}: 'gate_bindings' must be a list")

    gates: list[config.Gate] = []
    notes: list[str] = []
    for index, entry in enumerate(raw):
        try:
            gate = config.parse_gate(entry, index, where, allow_proves=True)
        except config.ConfigError as exc:
            raise SpecError(str(exc)) from exc
        if not gate.proves:
            raise SpecError(
                f"{where}: gate_bindings[{index}] ('{gate.id}') names no "
                "'proves'. This file is the binding channel and nothing else; "
                "a gate that evidences no criterion belongs in the spec's own "
                "'gates:' block, where it already goes"
            )
        gates.append(gate)

    # **The criteria join runs on EVERY parsed binding, before any is
    # dropped**, and the order was wrong the first time this was written: a
    # binding that is both a duplicate and invalid — bound to a `human:`
    # criterion, bound to a criterion nobody declared, the second gate for one
    # criterion — was being dropped as a duplicate and never reaching the
    # refusal that matters. Three existing tests caught it. A duplicate is a
    # QUALITY objection; these are VALIDITY, and validity comes first.
    try:
        config.check_bindings(gates, {c.id: c for c in criteria}, where)
    except config.ConfigError as exc:
        raise SpecError(str(exc)) from exc

    kept: list[config.Gate] = []
    applied: list[str] = []
    # What the CONFIG already proves, so the note below can stop claiming a
    # criterion is unbound when the file on disk says otherwise.
    bound_already = {
        other.proves for other in declared if getattr(other, "proves", None)
    }
    for gate in gates:
        twin = next(
            (other for other in declared if same_command(other.run, gate.run)),
            None,
        )
        if twin is None:
            kept.append(gate)
            continue
        if twin.id == gate.id and twin.proves == gate.proves:
            # **ALREADY APPLIED, and this is not a conflict** — field report
            # 2026-08-21 finding 10. A previous run installed this exact gate
            # and left the proposal in the sidecar, so the next run compared
            # the gate to ITSELF, found "a twin", and refused. The message it
            # produced was wrong three ways: it named the same id on both
            # sides of the sentence, it asserted the gate "passes today" about
            # a gate that exits 1, and it said the criterion was left unbound
            # while `.wringer.yaml` carried its `proves:` line.
            #
            # Then it stopped the build, and recovery meant moving the
            # already-applied proposal aside by hand. Re-running a verb must
            # be a safe act; a second run that refuses because the first one
            # succeeded is a trap with no way out for the person who set it.
            #
            # The id AND the command AND the binding must all match. Same
            # command under a different id is a real conflict and falls
            # through; same id proving something else is a real change and
            # falls through too.
            applied.append(
                f"{where}: '{gate.id}' is already installed and runs the same "
                "command, so there is nothing to add for it. It was installed "
                "on an earlier run"
            )
            continue
        # **No claim about whether it passes.** The sentence here used to end
        # "it passes today, so it cannot be made to fail by the work" — a
        # statement about a gate result that nothing had run. On the measured
        # case it was simply false: the command exits 1, and Wringer itself
        # had reported "None of them passes today" one run earlier. The
        # ARGUMENT survives where it always lived, in the drafting request's
        # prose; what cannot survive is asserting a result nobody measured.
        unbound = "" if gate.proves in bound_already else (
            f", and nothing else in the project's settings proves "
            f"'{gate.proves}'"
        )
        notes.append(
            f"{where}: '{gate.id}' runs `{gate.run}`, which is already what "
            f"'{twin.id}' runs. A check that already runs cannot be the thing "
            f"that proves '{gate.proves}': proving it needs a check that can "
            f"tell the difference this work makes. The binding was dropped"
            f"{unbound}"
        )
    return tuple(kept), tuple(notes), tuple(applied)


def parse_gatespec(
    data: Any, where: str, criteria: Any, declared: Any = ()
) -> tuple[config.Gate, ...]:
    """Read `wringer.gates.yaml` — hand-written or drafted, same parser.

    **A duplicate here RAISES rather than being dropped with a note**, and the
    asymmetry with the drafted path is deliberate. A drafted reply is one
    model's proposal and dropping one unusable entry saves the rest; a sidecar
    is a file somebody wrote on purpose, and silently ignoring a line they
    typed is worse for them than refusing it to their face.
    """
    if not isinstance(data, dict):
        raise SpecError(f"{where}: top level must be a mapping")
    unknown = sorted(set(data) - _GATESPEC_KEYS)
    if unknown:
        raise SpecError(f"{where}: unknown keys: {', '.join(unknown)}")
    version = data.get("schema_version")
    if version != GATESPEC_SCHEMA_VERSION:
        raise SpecError(
            f"{where}: 'schema_version: {GATESPEC_SCHEMA_VERSION}' is "
            f"required (got {version!r})"
        )
    # **`already` is deliberately not raised on** — field report 2026-08-21
    # finding 10. This function refuses a sidecar entry it cannot use, because
    # a sidecar is a file somebody wrote on purpose and silently ignoring a
    # line they typed is worse than refusing it to their face. But a proposal
    # this repository ALREADY INSTALLED is not an entry it cannot use: it is
    # the previous run's success, still sitting where the previous run left
    # it. Refusing it made a second `wringer-drive run` impossible without a
    # hand edit, and there is no version of "re-running is dangerous" that
    # this product can afford.
    gates, notes, _already = parse_bindings(
        data.get("gates"), criteria, where, declared
    )
    if notes:
        raise SpecError(notes[0])
    return gates


