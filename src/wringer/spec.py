def authorising_sha256(root: Path) -> str | None:
    """The hash of the spec that authorised this work, if there is one.

    `wringer.spec.yaml` is the document a human approved — the `approved:
    true` in it is the authority everything downstream runs on. Nothing
    recorded *which* spec that was, so `wring attest`'s first clause
    ("authorized by spec S") had nothing to point at, and a spec could be
    edited after approval with no trace.

    Cheap here, impossible later: this goes into manifests whose schemas stop
    being amendable when 0.2.0 tags.
    """
    import hashlib

    path = root / SPEC_FILENAME
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def load(path: Path) -> Spec:
    """Read and validate `wringer.spec.yaml`.

    Re-read from disk on every `wring plan`, never cached and never carried
    over from the drafting run: `approved` means what the file says now.
    """
    if not path.is_file():
        raise SpecError(
            f"no {path.name} in {path.parent} — draft one with "
            f"'wring spec <PRD.md>'"
        )
    raw_bytes = path.read_bytes()
    if len(raw_bytes) > MAX_SPEC_BYTES:
        raise SpecError(
            f"{path.name} is {len(raw_bytes)} bytes, over the "
            f"{MAX_SPEC_BYTES}-byte limit"
        )
    try:
        data = yaml.safe_load(raw_bytes.decode("utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise SpecError(f"{path.name} is not valid YAML: {exc}") from exc
    return parse(data, path.name)


def parse(data: Any, where: str) -> Spec:
    """Validate a spec mapping — strict, like every other loader here."""
    if not isinstance(data, dict):
        raise SpecError(f"{where}: top level must be a mapping")

    unknown = sorted(set(data) - _TOP_LEVEL_KEYS)
    if unknown:
        raise SpecError(f"{where}: unknown keys: {', '.join(unknown)}")

    declared = data.get("schema_version")
    if declared != SCHEMA_VERSION:
        raise SpecError(
            f"{where}: 'schema_version: {SCHEMA_VERSION}' is required "
            f"(got {declared!r})"
        )

    approved = data.get("approved")
    if not isinstance(approved, bool):
        raise SpecError(
            f"{where}: 'approved' must be a boolean, and must be present — it "
            "is the interlock, so a spec that forgot to say is not approved by "
            "omission"
        )

    title = _nonempty(data.get("title"), f"{where}: 'title'")
    intent = _nonempty(data.get("intent"), f"{where}: 'intent'")

    questions = _parse_questions(data.get("open_questions"), where)

    criteria_raw = data.get("criteria")
    try:
        _, criteria = parse_document(
            {
                "schema_version": "wringer.rubric.v1",
                "title": title,
                "criteria": criteria_raw,
            },
            where,
        )
    except RubricError as exc:
        raise SpecError(str(exc)) from exc

    gates_raw = data.get("gates") or []
    if not isinstance(gates_raw, list):
        raise SpecError(f"{where}: 'gates' must be a list")
    try:
        gates = tuple(
            config.parse_gate(entry, index, where)
            for index, entry in enumerate(gates_raw)
        )
    except config.ConfigError as exc:
        raise SpecError(str(exc)) from exc
    seen: set[str] = set()
    for gate in gates:
        if gate.id in seen:
            raise SpecError(f"{where}: duplicate gate id '{gate.id}'")
        seen.add(gate.id)

    tasks = _parse_tasks(data.get("tasks"), where)

    return Spec(
        approved=approved,
        title=title,
        intent=intent,
        questions=questions,
        criteria=criteria,
        gates=gates,
        tasks=tasks,
        path=where,
    )


def _nonempty(value: Any, at: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise SpecError(f"{at} must be a non-empty string")
    return value


def _slug(value: Any, at: str) -> str:
    identifier = _nonempty(value, at)
    if len(identifier) > config.MAX_GATE_ID_LENGTH or not (
        config.GATE_ID_PATTERN.fullmatch(identifier)
    ):
        raise SpecError(
            f"{at} ('{identifier}') must be a slug — letters, digits, '-' and "
            "'_', starting with a letter or digit"
        )
    return identifier


def _parse_questions(raw: Any, where: str) -> tuple[Question, ...]:
    if raw is None:
        return ()
    if not isinstance(raw, list):
        raise SpecError(f"{where}: 'open_questions' must be a list")
    if len(raw) > MAX_OPEN_QUESTIONS:
        raise SpecError(
            f"{where}: {len(raw)} open questions, over the limit of "
            f"{MAX_OPEN_QUESTIONS} — a spec that unclear needs a conversation, "
            "not a form"
        )

    questions: list[Question] = []
    seen: set[str] = set()
    for index, entry in enumerate(raw):
        at = f"{where}: open_questions[{index}]"
        if not isinstance(entry, dict):
            raise SpecError(f"{at} must be a mapping")
        unknown = sorted(set(entry) - _QUESTION_KEYS)
        if unknown:
            raise SpecError(f"{at}: unknown keys: {', '.join(unknown)}")

        question_id = _slug(entry.get("id"), f"{at}: 'id'")
        if question_id in seen:
            raise SpecError(f"{at}: duplicate question id '{question_id}'")
        seen.add(question_id)

        required = entry.get("required", True)
        if not isinstance(required, bool):
            raise SpecError(f"{at} ('{question_id}'): 'required' must be a boolean")
        answer = entry.get("answer", "")
        if answer is None:
            answer = ""
        if not isinstance(answer, str):
            raise SpecError(f"{at} ('{question_id}'): 'answer' must be a string")

        questions.append(
            Question(
                id=question_id,
                question=_nonempty(entry.get("question"), f"{at}: 'question'"),
                required=required,
                answer=answer,
            )
        )
    return tuple(questions)


def _parse_tasks(raw: Any, where: str) -> tuple[Task, ...]:
    if not isinstance(raw, list) or not raw:
        raise SpecError(f"{where}: 'tasks' must be a non-empty list")
    if len(raw) > MAX_TASKS:
        raise SpecError(
            f"{where}: {len(raw)} tasks, over the limit of {MAX_TASKS} — a "
            "single drafting pass proposing that many was not understanding "
            "the PRD"
        )

    tasks: list[Task] = []
    seen: set[str] = set()
    for index, entry in enumerate(raw):
        at = f"{where}: tasks[{index}]"
        if not isinstance(entry, dict):
            raise SpecError(f"{at} must be a mapping")
        unknown = sorted(set(entry) - _TASK_KEYS)
        if unknown:
            raise SpecError(f"{at}: unknown keys: {', '.join(unknown)}")

        # The same slug rule as a fleet task id, because this becomes one.
        task_id = _slug(entry.get("id"), f"{at}: 'id'")
        if task_id in seen:
            raise SpecError(f"{at}: duplicate task id '{task_id}'")
        seen.add(task_id)

        brief = _nonempty(entry.get("brief"), f"{at} ('{task_id}'): 'brief'")
        _check_contained(brief, f"{at} ('{task_id}'): 'brief'")
        directory = entry.get("dir", ".")
        if not isinstance(directory, str) or not directory.strip():
            raise SpecError(f"{at} ('{task_id}'): 'dir' must be a non-empty string")
        _check_contained(directory, f"{at} ('{task_id}'): 'dir'")

        tasks.append(
            Task(
                id=task_id,
                brief=brief,
                objective=_nonempty(
                    entry.get("objective"), f"{at} ('{task_id}'): 'objective'"
                ),
                dir=directory,
            )
        )
    return tuple(tasks)


def unanswerable_questions(questions: Any, files: Any = ()) -> tuple[Any, ...]:
    """Required questions that name a file in this repository.

    **Field report 2026-08-21, finding 5.** A required, blocking question on a
    real run was:

        Which of the listed criteria does `acceptance/test_skip_downstream.py`
        (with `acceptance/chain.json`) actually assert, so the remaining
        criteria can be given checks of their own?

    Answering that means reading a 145-line pytest file and mapping ten test
    functions onto nine acceptance criteria. **That is a question for an
    engineer**, asked of a product manager, as the thing blocking their build
    — and it contradicts the product's stated audience on the one screen where
    the audience matters.

    The drafter is not guessing when it does this: the request HANDS it the
    repository's tracked file list, precisely so rule 6 is satisfiable. So a
    question naming one of those files is a question about something the
    drafter could have looked at, and the request already says *"never ask
    what you can look up"*. Prompts are not guards; this is the guard.

    **The parser REFUSES the whole reply. It never rewrites a question and
    never demotes one to optional** — standing law. Rewriting would mean this
    package deciding what the drafter meant to ask, and demoting would leave a
    question nobody can answer sitting in the spec looking optional.

    Only REQUIRED questions count. An optional question mentioning a file
    blocks nothing, and refusing a paid draft over it would cost more than it
    saves.
    """
    tracked = {str(name) for name in (files or ()) if str(name).strip()}
    if not tracked:
        # Nothing to check against. **Not a pass** — an unchecked condition,
        # and saying so matters: an offline draft with no listing gets no
        # protection here, rather than a clean bill.
        return ()
    # Match on the BASENAME too, because a drafter naming
    # `acceptance/test_skip_downstream.py` and one naming
    # `test_skip_downstream.py` are asking the identical unanswerable
    # question. Directories are excluded: a question mentioning `src` or
    # `tests` in passing is ordinary English, not a lookup.
    # **A tracked path that is a bare word is not evidence of a lookup.**
    # `LICENSE` and `Makefile` are real tracked files AND ordinary English
    # words, so matching them would refuse a draft for asking "should this be
    # covered by the same LICENSE?" — a guard that sometimes lies, which
    # SPEC_GATEGEN ruling 4 already refused by name. A path only counts when
    # it carries a directory separator or an extension, which is what makes it
    # unmistakably a path rather than a word. Caught by the test that asserts
    # it, not by writing this carefully the first time.
    names = {path for path in tracked if "/" in path or "." in path}
    for path in tracked:
        base = path.rsplit("/", 1)[-1]
        if "." in base:
            names.add(base)
    found = []
    for question in questions or ():
        if not getattr(question, "required", True):
            continue
        text = str(getattr(question, "question", ""))
        if any(name in text for name in names):
            found.append(question)
    return tuple(found)


def _is_promotion(identifier: str, entry: dict, questions: Any) -> bool:
    """Whether this id is in both documents because somebody OVERRULED it.

    **Found by executing, 2026-08-21, not by reading.** The collision rule
    above drops any assumption whose id is also a question's, to stop two
    readers joining an unrelated decision to an unrelated answer. Correct for
    a COINCIDENCE — and a promotion is not one. `wringer-board revise` turns
    an assumption into an answered open question and deliberately leaves the
    sidecar row in place, so after any override the id is legitimately in both
    files. The drop then deleted exactly the rows the stale-criteria check
    exists to read, and it did so silently.

    Told apart the way `revise` and the plan already tell it apart: **by the
    words, not by the id.** A promotion's question text IS the question the
    assumption recorded displacing. A coincidence's is something else, and
    still drops.
    """
    displaced = str(entry.get("instead_of_asking") or "").strip()
    if not displaced:
        return False
    for question in questions:
        if getattr(question, "id", None) != identifier:
            continue
        # **Answered, AND the same words.** Matching words alone is not
        # enough: a single DRAFT can both ask a question and record deciding
        # it, phrased identically, and that is a contradiction to drop rather
        # than an override to keep — there was never a person in the loop.
        # `revise` always writes an answer, so a promotion always has one, and
        # requiring it is what separates "somebody overruled this" from "one
        # reply said both things at once".
        if not str(getattr(question, "answer", "") or "").strip():
            return False
        return str(getattr(question, "question", "")).strip() == displaced
    return False


def _criteria_refs(
    entry: dict, at: str, criteria: Any, notes: list[str]
) -> tuple[str, ...]:
    """The criteria an assumption says it shaped, minus any that do not exist.

    **A reference to a criterion nobody declared is DROPPED with a note, never
    a refusal.** The rest of the assumption is still consent-bearing and still
    worth showing a person; killing a paid draft over one stale id would be
    the `objective_note` mistake again. But a dangling reference cannot be
    kept either — it would make `wring plan` refuse on a criterion that does
    not exist, with no way for anyone to review it.
    """
    raw = entry.get("criteria")
    if raw is None:
        return ()
    if not isinstance(raw, list):
        notes.append(f"dropped {at}: 'criteria' must be a list of criterion ids")
        return ()
    declared = {getattr(c, "id", None) for c in criteria}
    kept: list[str] = []
    for value in raw:
        name = str(value).strip()
        if not name:
            continue
        if declared and name not in declared:
            notes.append(
                f"{at}: names criterion '{name}', which this spec does not "
                "declare. The reference was dropped; the decision was kept"
            )
            continue
        if name not in kept:
            kept.append(name)
    return tuple(kept)


def parse_assumptions(
    raw: Any, where: str, questions: Any = (), criteria: Any = ()
) -> tuple[tuple[Assumption, ...], tuple[str, ...]]:
    """Decisions taken instead of asking — the drafted or hand-written list.

    **A malformed entry DROPS with a note; it never refuses the draft.** Same
    asymmetry R3 ruled for a decorative key: a model's proposal survives with
    its losses named, because refusing a whole paid draft over one unusable
    row is the `objective_note` mistake. `approved` smuggled onto a row has
    already refused the reply in `_drop_unknown_reply_keys`, above.

    **The collision rule is narrow, and it was too broad in the first draft.**
    An assumption whose id matches an open question is only a CONTRADICTION —
    a draft claiming both to have decided a thing and to be still asking it —
    when that question is REQUIRED AND UNANSWERED. Refusing every collision
    would kill whole paid drafts on measured drafter behaviour; anything else
    is a note, and the plan renders the cross-reference.
    """
    if raw is None:
        return (), ()
    if not isinstance(raw, list):
        raise SpecError(f"{where}: 'assumptions' must be a list")
    if len(raw) > MAX_ASSUMPTIONS:
        raise SpecError(
            f"{where}: {len(raw)} assumptions, over the limit of "
            f"{MAX_ASSUMPTIONS} — approving a plan approves every one of them, "
            "and a list nobody can read is not consent"
        )

    blocking = {
        q.id for q in questions
        if getattr(q, "required", True) and not getattr(q, "answered", False)
    }
    # **Every OTHER collision drops with a note, and narrowing this to the
    # blocking case alone was a real defect.** An assumption sharing an id with
    # an optional or already-answered question was accepted silently — and both
    # readers of this file then join assumption to question BY ID, which is the
    # fallacy `carry_answers_forward` exists to refuse, reintroduced inside the
    # consent surface itself. The plan printed "you answered this" quoting an
    # unrelated answer, and `revise` overwrote that answer instead of promoting
    # the assumption.
    #
    # The request already gives the drafter the TOTAL rule ("an `assumptions`
    # id must not be the id of a question you are also asking"). This is that
    # rule as a guard, and the file's own comment says why: prompts are not
    # guards.
    every_question = {getattr(q, "id", None) for q in questions}
    kept: list[Assumption] = []
    notes: list[str] = []
    seen: set[str] = set()
    for index, entry in enumerate(raw):
        at = f"{where}: assumptions[{index}]"
        if not isinstance(entry, dict):
            notes.append(f"dropped {at}: not a mapping")
            continue
        try:
            identifier = _slug(entry.get("id"), f"{at}: 'id'")
            assumption = Assumption(
                id=identifier,
                decision=_nonempty(entry.get("decision"), f"{at}: 'decision'"),
                why=_nonempty(entry.get("why"), f"{at}: 'why'"),
                # REQUIRED, and non-empty: `wringer-board revise` turns this
                # into an open question's `question:`, and an empty one would
                # write a spec the engine's own loader refuses.
                instead_of_asking=_nonempty(
                    entry.get("instead_of_asking"), f"{at}: 'instead_of_asking'"
                ),
                criteria=_criteria_refs(entry, at, criteria, notes),
            )
        except SpecError as exc:
            # `exc` already begins with `at`; prefixing again said it twice.
            notes.append(f"dropped assumption: {exc}")
            continue
        if identifier in seen:
            notes.append(f"dropped {at}: duplicate assumption id '{identifier}'")
            continue
        # **An assumption may never displace a judgement only a person can
        # make** — field report 2026-08-22 finding 9, and a REFUSAL rather than
        # a note on purpose.
        #
        # Run 4 of that day moved the heading wording into `DECIDED WITHOUT
        # ASKING YOU` — the same criterion the board describes to the reader as
        # *"No check can decide this one — it needs a person to look and say."*
        # Run 3, same PRD and same model, had asked. So the one decision the
        # document itself says no check can make is the one the drafter chose
        # to take, and a person approving the plan would have shipped wording
        # they never picked.
        #
        # Everything else in this parser drops a bad row and keeps the paid
        # draft, and that asymmetry is deliberate and stays. This is the case
        # it does not cover: `human: true` is the spec's own statement that
        # nothing but a person settles this, so an assumption over it is not a
        # row to salvage — it is the consent surface answering on the person's
        # behalf in the one place it has no standing. Salvaging the rest would
        # leave the criterion in the plan with the decision already taken.
        #
        # Narrow by construction: it fires only on criteria the drafter ITSELF
        # marked `human: true` and ITSELF named in `criteria:`. A drafter that
        # asks the question instead is untouched, which is what run 3 did.
        judged_by_a_person = sorted(
            name
            for name in assumption.criteria
            if any(
                getattr(c, "id", None) == name and getattr(c, "human", False)
                for c in criteria
            )
        )
        if judged_by_a_person:
            raise SpecError(
                f"{at}: '{identifier}' decides something that shapes "
                f"{', '.join(repr(n) for n in judged_by_a_person)}, which this "
                "same reply marks 'human: true' — only a person can settle it. "
                "A decision taken without asking cannot stand in for the one "
                "judgement no check is allowed to make. Ask the question "
                "instead. Nothing was written"
            )
        if identifier in blocking:
            raise SpecError(
                f"{at}: '{identifier}' is both an assumption and a required, "
                "unanswered open question — the reply says it decided this and "
                "that it still needs to ask about it. One draft cannot do both, "
                "and a person must never be shown that pair. Nothing was written"
            )
        if identifier in every_question and not _is_promotion(
            identifier, entry, questions
        ):
            notes.append(
                f"dropped {at}: '{identifier}' is also an open question's id, "
                "and an id is not a question. Kept as the question, because a "
                "decision and a question sharing an id is a pair two readers "
                "would join wrongly"
            )
            continue
        seen.add(identifier)
        kept.append(assumption)
    return tuple(kept), tuple(notes)


def lift_outcomes(drafted: dict) -> tuple[dict, dict[str, str]]:
    """Take each task's plain-language `outcome` off the reply, keyed by task id.

    **Called BEFORE `_drop_unknown_reply_keys`, and that ordering is the whole
    mechanism.** `outcome` is not in `_TASK_KEYS`, so the drop-walk would eat
    it with a note — correct behaviour for a decorative key, wrong for this
    one.

    **And `_TASK_KEYS` does NOT gain it.** That set is what `parse` — the
    loader every on-disk `wringer.spec.yaml` faces — accepts, and
    `spec.schema.json`'s task items are `additionalProperties: false` and
    frozen. Adding it there would make the loader accept a key the schema
    refuses: a spec that loads and fails its own published shape.

    So the sentence travels in the reply, is lifted here, and lands in the
    sidecar beside the assumptions. The task the engineer works from is
    untouched.
    """
    lifted: dict[str, str] = {}
    notes: list[str] = []
    cleaned = dict(drafted)
    tasks = drafted.get("tasks")
    if not isinstance(tasks, list):
        return cleaned, lifted, ()
    rebuilt: list[Any] = []
    for index, entry in enumerate(tasks):
        if not isinstance(entry, dict) or "outcome" not in entry:
            rebuilt.append(entry)
            continue
        outcome = entry.get("outcome")
        identifier = str(entry.get("id", ""))
        if isinstance(outcome, str) and outcome.strip() and identifier:
            lifted[identifier] = outcome.strip()
        else:
            # **Named, never silent.** This runs BEFORE the drop-walk and
            # removes the key, so the drop-walk can never report it — which
            # made this the one place in the parser where a model's content
            # disappeared without a word, against the rule R3 exists to state.
            # Worse, when a sibling task supplied a valid outcome, the missing-
            # outcome note below then said this task "has no plain-language
            # outcome" about a reply that carried one.
            carried = str(outcome).strip().splitlines()
            notes.append(
                f"dropped from the drafted reply: tasks[{index}] "
                f"('{identifier or '?'}') carried an unusable 'outcome' — "
                + (carried[0][:100] if carried else "it carried nothing")
            )
        rebuilt.append({k: v for k, v in entry.items() if k != "outcome"})
    cleaned["tasks"] = rebuilt
    return cleaned, lifted, tuple(notes)


def parse_outcomes(
    raw: Any, tasks: Any, where: str
) -> tuple[dict[str, str], tuple[str, ...]]:
    """Outcomes from a sidecar on disk, checked against the tasks beside them.

    **A row naming a task the spec does not have is refused whole** — content
    pointing at nothing, which is the rule `config.check_bindings` already
    applies to a `proves` naming no criterion. A MISSING outcome is the
    opposite case and is not an error at all: nothing was lost, something is
    absent, and refusing a paid draft over an absent sentence is the
    `objective_note` mistake.
    """
    if raw is None:
        return {}, ()
    if not isinstance(raw, list):
        raise SpecError(f"{where}: 'outcomes' must be a list")
    known = {getattr(task, "id", None) or (task or {}).get("id") for task in tasks}
    found: dict[str, str] = {}
    notes: list[str] = []
    for index, entry in enumerate(raw):
        at = f"{where}: outcomes[{index}]"
        if not isinstance(entry, dict):
            notes.append(f"dropped {at}: not a mapping")
            continue
        task_id = str(entry.get("task", ""))
        if task_id not in known:
            raise SpecError(
                f"{at}: names task '{task_id}', which this spec does not have. "
                f"Its tasks are: {', '.join(sorted(str(k) for k in known if k))}. "
                "Nothing was written"
            )
        text = entry.get("outcome")
        if not isinstance(text, str) or not text.strip():
            notes.append(f"dropped {at} ('{task_id}'): 'outcome' must be a sentence")
            continue
        found[task_id] = text.strip()
    return found, tuple(notes)


def missing_outcome_notes(tasks: Any, outcomes: dict[str, str]) -> tuple[str, ...]:
    """Tasks with no plain-language outcome — but ONLY once the reply uses the
    channel at all.

    **The scoping rule is not tidiness; without it this reddens a green test.**
    `test_a_binding_with_a_command_of_its_own_is_kept` asserts `notes == ()`
    totally, and its fixture is an archived capture that predates `outcome`.
    A per-task note there would fill `notes` and break the watch that the
    duplicate-binding rule refuses duplicates AND NOTHING ELSE.

    Loosening that assertion instead was considered and refused: it would
    destroy exactly the property the test exists for. A drafter that was never
    asked for outcomes is not a drafter that omitted them.
    """
    if not outcomes:
        return ()
    return tuple(
        f"task '{task.id}' has no plain-language outcome — the plan will show "
        "the engineer's objective for it and say that no outcome was written"
        for task in tasks
        if task.id not in outcomes
    )


def _carried_id(identifier: str, taken: set[str]) -> str:
    """An id for a carried answer that always fits, however many redrafts run.

    Suffixes are REPLACED rather than accumulated, and the stem is truncated so
    the result always satisfies `_slug` — letters, digits, '-' and '_', at most
    `config.MAX_GATE_ID_LENGTH`. A previous version appended `-as-answered`
    each time and eventually produced an id the spec's own loader refused,
    which wedged `--redraft` permanently.
    """
    limit = config.MAX_GATE_ID_LENGTH
    stem = re.sub(r"-answered(-\d+)?$", "", identifier)
    for attempt in range(2, 1000):
        suffix = f"-answered-{attempt}" if attempt > 2 else "-answered"
        candidate = stem[: max(1, limit - len(suffix))] + suffix
        if candidate not in taken:
            return candidate
    # 998 carried copies of one question is not a document anybody has; falling
    # back to the stem keeps this total rather than raising from bookkeeping.
    return stem[:limit]


def carry_answers_forward(
    drafted: Spec, previous: Spec
) -> tuple[Spec, tuple[str, ...]]:
    """Re-draft: keep every answer the person already gave. **An id is not a
    question.**

    Restoring an answer on id match alone attaches a person's answer to words
    they never read. Measured on this repository's own captures: the id
    `what-counts-as-played` carries FOUR materially different questions across
    four rolls of one unchanged PRD —

        run 2: "...or only after they have actually played for a while
                (and if so, how long)?"
        run 3: "...or only after they actually start a round
                (e.g. press start / the game begins)?"

    Someone who answered run 2's with *"after about thirty seconds"* would
    have that filed as their answer to run 3's question about pressing start.
    **That manufactures a consent nobody gave**, which is the defect this whole
    surface exists to prevent — and the feature meant to PROTECT answers would
    have been the thing that forged one.

    So the join is on TEXT, and the three outcomes are:

    - same id, byte-equal question -> the answer is restored;
    - same id, different wording   -> the previous pair is carried forward as
      its OWN entry, so the answer stays under the words it answered, and the
      newly worded question stays required and unanswered so `wring plan`
      refuses until the person answers it;
    - id absent from the new draft -> carried forward with its answer intact.

    Nothing is discarded and nothing is re-pointed.
    """
    answered = {q.id: q for q in previous.questions if q.answered}
    if not answered:
        return drafted, ()

    notes: list[str] = []
    merged: list[Question] = []
    carried: list[Question] = []
    for question in drafted.questions:
        was = answered.get(question.id)
        if was is None:
            merged.append(question)
            continue
        if was.question == question.question:
            merged.append(
                Question(
                    id=question.id,
                    question=question.question,
                    required=question.required,
                    answer=was.answer,
                )
            )
            continue
        # Same id, different words. The answer keeps its own question.
        notes.append(
            f"'{question.id}' was re-worded by this draft, so your previous "
            "answer was NOT moved onto it — an id is not a question. The "
            "answer is kept under the wording you answered, and the new "
            "wording is left for you to answer"
        )
        merged.append(question)
        carried.append(was)

    for identifier, question in answered.items():
        if identifier in {q.id for q in drafted.questions}:
            continue
        notes.append(
            f"'{identifier}' is not in the new draft, so it was carried "
            "forward with your answer rather than dropped"
        )
        carried.append(question)

    # **The merge may not grow past the loader's own ceiling, and the first
    # version could.** Carried answers accumulate across redrafts; once the
    # total passed `MAX_OPEN_QUESTIONS` the re-parse refused, nothing was
    # written, and — because nothing was written — every later redraft
    # produced the identical refusal forever. That is the same permanent wedge
    # as the id-length one, on a different limit.
    #
    # So the oldest carried answers are dropped, LOUDLY, rather than the
    # document becoming unwritable. Losing the oldest answer with a sentence
    # naming it is bad; losing the ability to draft ever again is worse.
    room = MAX_OPEN_QUESTIONS - len(merged)
    if len(carried) > max(room, 0):
        for question in carried[: len(carried) - max(room, 0)]:
            notes.append(
                f"'{question.id}' could NOT be carried forward — this spec is "
                f"at the limit of {MAX_OPEN_QUESTIONS} questions. Your answer "
                f"to it was: {question.answer.strip()[:120]}"
            )
        carried = carried[len(carried) - max(room, 0):]

    if carried:
        # A carried pair keeps its id only when nothing else claims it.
        #
        # **BOUNDED AND IDEMPOTENT, and the first version was neither.** It
        # appended `-as-answered` in a loop, so each redraft that re-worded a
        # question grew the carried id by twelve characters. `_slug` caps an id
        # at 64, so a realistic question id wedged the repository on the second
        # or third redraft: the merged document no longer parsed, the re-parse
        # refused, nothing was written — and because nothing was written, every
        # later redraft produced the byte-identical refusal forever. The only
        # way out was deleting `wringer.spec.yaml`, which is exactly the
        # answer-losing move the refusal above steers people away from.
        #
        # A carried pair's id is BOOKKEEPING, not content. It must never be
        # able to make the person's document unloadable.
        taken = {q.id for q in merged}
        renamed = []
        for question in carried:
            identifier = _carried_id(question.id, taken)
            taken.add(identifier)
            renamed.append(
                Question(
                    id=identifier,
                    question=question.question,
                    required=question.required,
                    answer=question.answer,
                )
            )
        merged.extend(renamed)

    from dataclasses import replace as _replace

    return _replace(drafted, questions=tuple(merged)), tuple(notes)


def buried_decision_notes(criteria: Any) -> tuple[str, ...]:
    """Criteria whose `guidance` looks like it carries a DECISION.

    **A lower bound, and every caller must treat it as one.** See
    `_BURIED_DECISION_MARKERS`: the list has been wrong twice, there is no
    true-negative case in the corpus, and no structural check can replace it.
    A criterion this does not name has NOT been shown to be free of buried
    decisions — only to avoid the phrasings measured so far.

    It notes and never rewrites. Moving the prose into `assumptions` would be
    this parser inventing a decision, which is the self-answered-question
    refusal wearing a different coat.
    """
    found: list[str] = []
    for criterion in criteria or ():
        guidance = str(getattr(criterion, "guidance", "") or "")
        lowered = guidance.lower()
        if not any(marker in lowered for marker in _BURIED_DECISION_MARKERS):
            continue
        cid = getattr(criterion, "id", "?")
        found.append(
            f"criterion '{cid}' appears to state a DECISION inside its "
            "guidance, where the person approving the plan will not read it "
            f"as one: {guidance.strip().splitlines()[0][:120]}"
        )
    if found:
        found.append(
            f"{len(found)} criteria named — AT LEAST that many, never a total. "
            "This check matches measured phrasings and its silence is not "
            "evidence that the rest are free of decisions"
        )
    return tuple(found)


def _check_contained(candidate: str, at: str) -> None:
    """Refuse any path that could leave the repository.

    `wring plan` **writes** brief files at these paths, and the paths were
    proposed by a model. An absolute path or a `..` here is the difference
    between generating a document and overwriting `~/.ssh/config`. Checked on
    the string, before any filesystem call, so a symlink cannot answer for it.
    """
    # Before any Path() call: a NUL reaches the OS layer and raises ValueError
    # out of stat(), which is a crash where a refusal belongs.
    if any(ch == "\x00" or (ch < " " and ch not in "\t") for ch in candidate):
        raise SpecError(f"{at} contains a control character")
    path = Path(candidate)
    if path.is_absolute() or candidate.startswith("~"):
        raise SpecError(f"{at} must be a path relative to the repository root")
    if ".." in path.parts:
        raise SpecError(f"{at} must not escape the repository with '..'")


def resolve_inside(root: Path, candidate: str, at: str) -> Path:
    """The absolute path for a spec-declared relative path, or refuse it.

    Belt and braces over `_check_contained`: that one reads the string, this
    one resolves it and checks the answer is still under `root`, which is what
    catches a symlinked directory pointing out of the tree.
    """
    _check_contained(candidate, at)
    resolved = (root / candidate).resolve()
    if not resolved.is_relative_to(root.resolve()):
        raise SpecError(f"{at} resolves outside the repository ({resolved})")
    return resolved


# Files `wring plan` writes itself, or that describe the work. A spec-declared
# brief pointing at one of these would destroy the artifact plan just produced
# — and plan would then report having written it.
RESERVED_WRITE_PATHS = (
    SPEC_FILENAME,
    TASKS_FILENAME,
    RUBRIC_FILENAME,
    config.CONFIG_FILENAME,
)


def check_writable(root: Path, candidate: str, at: str) -> Path:
    """Resolve a path `wring plan` is about to WRITE, or refuse it.

    Everything `resolve_inside` refuses, plus the hazards that only matter
    because this end of the path is a write and a model chose it.
    """
    resolved = resolve_inside(root, candidate, at)
    relative = resolved.relative_to(root.resolve())

    if relative.parts and relative.parts[0] == ".git":
        raise SpecError(
            f"{at} points inside .git/ — Wringer never writes git state, and a "
            "brief that did would corrupt the repository rather than describe "
            "a task"
        )
    if relative.as_posix() in RESERVED_WRITE_PATHS:
        raise SpecError(
            f"{at} names {relative.as_posix()}, which `wring plan` writes or "
            "reads itself — writing a brief over it would destroy the plan and "
            "then report success"
        )
    if resolved.is_dir():
        raise SpecError(f"{at} names an existing directory")
    # A parent that exists and is not a directory makes mkdir raise *after*
    # earlier files are already on disk — the half-ran state the caller
    # promises is impossible. Catch it while nothing has been written.
    for parent in relative.parents:
        candidate_parent = root / parent
        if candidate_parent.exists() and not candidate_parent.is_dir():
            raise SpecError(
                f"{at}: '{parent.as_posix()}' exists and is not a directory"
            )
    return resolved


