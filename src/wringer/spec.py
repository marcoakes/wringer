def render_decisions(assumptions: Any, outcomes: Any = None) -> str:
    """`wringer.decisions.yaml` — what was decided FOR the person.

    The header is the NARROW TRUE CLAIM, and getting it narrow took a review.
    An earlier draft said flatly "NO AUTHORITY" while the same document gave
    this file the power to make `wring plan` refuse. A false sentence shipped
    inside the artifact it describes is the worst available place to put one.
    """
    lines = [
        DECISIONS_MARKER,
        "#",
        "# NO AUTHORITY OVER WHAT IS BUILT: no gate here runs, nothing under",
        "# .wringer/ is written from it, and no builder is ever briefed from it.",
        "#",
        "# It has no authority over anything else either, TODAY. The `consent`",
        "# block is declared in the schema and NOTHING READS IT: the check it",
        "# describes was ruled owed, not built. An earlier version of this",
        "# header said the block `can make wring plan REFUSE` — that was false",
        "# when it was written, in the one file whose subject is what you were",
        "# told.",
        f"schema_version: {DECISIONS_SCHEMA_VERSION}",
    ]
    # **The header is only written when there is something under it.** An
    # `assumptions:` block with no entries, under the sentence "Approving the
    # plan approves these", asserts something about zero things — and the
    # claim this whole channel exists to make is that decisions taken for a
    # person are VISIBLE, never that none were taken.
    if assumptions:
        lines += [
            "",
            "# Decided without asking you. Approving the plan approves these — and",
            "# each one carries the question it displaced, so you can ask it after",
            "# all.",
            "assumptions:",
        ]
    for assumption in assumptions:
        lines += [
            # **Through `_scalar`, like every other field.** Written bare, an
            # id that YAML 1.1 resolves as a non-string — `on`, `no`, `yes`,
            # `off`, `true`, `123` — reads back as a bool or an int, and
            # `parse_assumptions` then DROPS the row: a consent record
            # vanishing between the write and the read. `_slug` accepts all of
            # them, so nothing upstream refuses one. Same class as the
            # `approved: False` corruption fixed in the board this morning.
            f"  - id: {_scalar(assumption.id)}",
            f"    decision: {_scalar(assumption.decision)}",
            f"    why: {_scalar(assumption.why)}",
            f"    instead_of_asking: {_scalar(assumption.instead_of_asking)}",
        ]
        # Written only when the drafter gave them. An empty `criteria: []`
        # would assert that this decision shaped no criterion, which is a
        # claim nothing here can make — absence means "not stated", and the
        # heuristic downstream says exactly that.
        if assumption.criteria:
            lines.append("    criteria:")
            lines += [f"      - {_scalar(name)}" for name in assumption.criteria]
    if outcomes:
        lines += [
            "",
            "# What each task means for the person who asked for it, beside the",
            "# `objective` the engineer works from. Two registers, and this is",
            "# the one the plan leads with.",
            "outcomes:",
        ]
        for task_id, outcome in outcomes.items():
            lines += [
                # Same reason as the assumption id above: a task id of `on` or
                # `no` written bare comes back as a bool, and `parse_outcomes`
                # then refuses the whole sidecar for naming a task that "does
                # not exist" — about a task that does.
                f"  - task: {_scalar(task_id)}",
                f"    outcome: {_scalar(outcome)}",
            ]
    return "\n".join(lines) + "\n"


def parse_decisions(
    data: Any, where: str, questions: Any = (), criteria: Any = ()
) -> tuple[tuple[Assumption, ...], tuple[str, ...]]:
    """Read `wringer.decisions.yaml` — drafted or hand-written, same parser.

    **Both versions are read, and will be forever.** `wring spec` writes v2;
    every v1 document already on disk stays readable, and a v1 document IS a
    valid v2 document — v2 only adds an optional `criteria` back-reference.
    A reader that accepted only the newest version would turn law 7's "new
    file, never a changed one" into a break by a different route.
    """
    if not isinstance(data, dict):
        raise SpecError(f"{where}: top level must be a mapping")
    unknown = sorted(set(data) - {"schema_version", "assumptions", "outcomes",
                                  "consent"})
    if unknown:
        raise SpecError(f"{where}: unknown keys: {', '.join(unknown)}")
    version = data.get("schema_version")
    if version not in DECISIONS_SCHEMA_VERSIONS:
        raise SpecError(
            f"{where}: 'schema_version: {DECISIONS_SCHEMA_VERSION}' is "
            f"required (got {version!r})"
        )
    return parse_assumptions(data.get("assumptions"), where, questions, criteria)


# **A hedge against a question that has been answered** — field report
# 2026-08-22 finding 10. Matched on the phrase a drafter actually produced
# rather than on a grammar: this is a stale-fallback detector, not a parser of
# English, and a pattern that tried to be one would fire on prose that merely
# discusses uncertainty.
_HEDGE = re.compile(
    r"\(\s*if\s+(?:it\s+is\s+|this\s+is\s+)?unanswered\b[^)]*\)"
    r"|\bif\s+unanswered\s*,",
    re.I,
)


def conditionals_on_answered_questions(loaded: Any) -> tuple[tuple[str, str], ...]:
    """Places the spec still hedges against an answer it already has.

    **Only meaningful once `unanswered` is empty**, and the caller is what
    guarantees that. `wring plan` refuses on unanswered required questions
    before it reaches this, so a surviving "if unanswered" there is stale by
    construction. Called against a spec that still has open questions, this
    would be a guess about which question the hedge meant, and it does not
    guess — it just reports what it found and lets the caller own the premise.

    Returns `(where, sentence)` pairs so the refusal can quote the person's
    own document back at them rather than describing it.
    """
    found: list[tuple[str, str]] = []

    def scan(where: str, text: Any) -> None:
        if not isinstance(text, str) or not text.strip():
            return
        for match in _HEDGE.finditer(text):
            snippet = " ".join(text[max(0, match.start() - 80):match.end()].split())
            found.append((where, ("..." if match.start() > 80 else "") + snippet))

    for task in getattr(loaded, "tasks", ()) or ():
        scan(f"task '{getattr(task, 'id', '?')}' objective",
             getattr(task, "objective", ""))
        scan(f"task '{getattr(task, 'id', '?')}' guidance",
             getattr(task, "guidance", ""))
    for criterion in getattr(loaded, "criteria", ()) or ():
        scan(f"criterion '{getattr(criterion, 'id', '?')}' guidance",
             getattr(criterion, "guidance", ""))
        scan(f"criterion '{getattr(criterion, 'id', '?')}' title",
             getattr(criterion, "title", ""))
    scan("intent", getattr(loaded, "intent", ""))
    return tuple(found)


