def declared_gate_ids(existing: str) -> set[str]:
    """The gate ids a config already has.

    Parsed properly when the file parses, because a missed id means proposing
    a duplicate — and a human who applied that diff would be left with a
    config their own loader rejects. The line scan is only the fallback for a
    file that does not parse at all, which still deserves a diff.
    """
    try:
        return {g.id for g in config.parse(yaml.safe_load(existing)).gates}
    except (config.ConfigError, yaml.YAMLError, AttributeError):
        import re

        return set(
            re.findall(
                r"^\s*-\s*id:\s*[\"']?([A-Za-z0-9][\w-]*)", existing, re.MULTILINE
            )
        )


def proposals(loaded: Spec, sidecar: Any = ()) -> tuple[config.Gate, ...]:
    """Every gate `wring plan` would propose: the spec's own block, then the
    sidecar's bindings.

    There are TWO sources and there always were — `wringer.spec.v1` has
    carried a `gates:` block since P2, and the sidecar is the channel that
    can additionally say which criterion a gate proves. The spec review
    caught that the collision between them was unspecified.

    **An id in both files is refused, never resolved.** Preferring either one
    silently would attach a drafted binding to a command the reader believes
    came from the other document, and the reader is the person about to
    install it by hand.
    """
    from_spec = {gate.id for gate in loaded.gates}
    clash = sorted(gate.id for gate in sidecar if gate.id in from_spec)
    if clash:
        named = ", ".join(f"'{gate_id}'" for gate_id in clash)
        raise SpecError(
            f"{GATESPEC_FILENAME} and {SPEC_FILENAME} both declare "
            f"{named}. One id, one definition: keep the binding in "
            f"{GATESPEC_FILENAME} and drop the entry from {SPEC_FILENAME}'s "
            "'gates:' block, or give one of them another id"
        )
    return (*loaded.gates, *sidecar)


def gate_diff(existing: str, proposed: Any) -> tuple[str, tuple[str, ...],
                                                     tuple[str, ...]]:
    """The change a human would have to make to `.wringer.yaml`, as a diff.

    Returns the diff text, the ids it would add, and the ids that already
    exist. Wringer prints this and stops: installing a gate is changing what
    "verified" means, and that is not a thing a drafter gets to do quietly.

    `proposed` is a sequence of gates rather than the `Spec` it used to be,
    because the sidecar is a second source and a binding cannot live on a
    `Spec` at all — `wringer.spec.v1` is frozen and `spec.parse` builds its
    gates with `allow_proves` off.
    """
    import difflib

    declared = declared_gate_ids(existing)
    fresh = tuple(g.id for g in proposed if g.id not in declared)
    already = tuple(g.id for g in proposed if g.id in declared)
    if not fresh:
        return "", fresh, already

    addition = []
    for gate in proposed:
        if gate.id not in fresh:
            continue
        addition += [f"  - id: {_scalar(gate.id)}", f"    run: {_scalar(gate.run)}"]
        if gate.timeout != config.DEFAULT_TIMEOUT_SECONDS:
            addition.append(f"    timeout: {gate.timeout}")
        if gate.optional:
            addition.append("    optional: true")
        if gate.proves:
            # The binding travels WITH the command, so one edit installs both
            # and nobody ends up with a gate whose purpose was left behind in
            # another file.
            addition.append(f"    proves: {gate.proves}")

    merged = _append_gates(existing, addition)
    if merged is None:
        # The change could not be expressed as an edit to this file without
        # risking a second `gates:` key — which YAML resolves by keeping the
        # LAST one, silently deleting every gate the repo already declared.
        # No diff is the honest answer; the caller prints the gates in words.
        return "", fresh, already

    before = existing.splitlines(keepends=True)
    proposed = merged.splitlines(keepends=True)
    # `a/` and `b/` so `git apply` accepts it as-is. The human is the intended
    # applier, but a diff a machine cannot apply is a diff nobody checked.
    diff = "".join(
        difflib.unified_diff(
            before,
            proposed,
            fromfile=f"a/{config.CONFIG_FILENAME}",
            tofile=f"b/{config.CONFIG_FILENAME}",
        )
    )
    return diff, fresh, already


def _append_gates(existing: str, addition: list[str]) -> str | None:
    """Put the new gates under the existing `gates:` key, or None if it cannot.

    Textual on purpose: a round-trip through a YAML dumper would reformat a
    file the human wrote, and a diff full of unrelated reflowing is a diff
    nobody reads.

    Returns **None** rather than appending a second `gates:` key when the
    existing one is not a block-style list — a flow-style `gates: [...]`, say.
    Two `gates:` keys is not a merge: YAML keeps the last, so the "purely
    additive" diff would delete every gate the repo already declared, and the
    reader would have applied it believing the opposite.
    """
    import re

    lines = existing.splitlines()
    block = "\n".join(addition)
    for index, line in enumerate(lines):
        if line.rstrip() != "gates:":
            continue
        end = index + 1
        while end < len(lines) and (
            not lines[end].strip() or lines[end].startswith((" ", "\t", "#"))
        ):
            end += 1
        # Back off over the blank lines that separate this block from the next
        # key, so the addition lands inside the gate list rather than pressed
        # up against whatever came after it.
        while end > index + 1 and not lines[end - 1].strip():
            end -= 1
        return "\n".join(lines[:end] + addition + lines[end:]) + "\n"

    if re.search(r"^gates\s*:", existing, re.MULTILINE):
        return None
    tail = "" if existing.endswith("\n") or not existing else "\n"
    return f"{existing}{tail}gates:\n{block}\n"


def tasks_file_is_generated(path: Path) -> bool:
    """Whether overwriting `tasks.jsonl` would destroy something else.

    There is no comment syntax in JSONL to leave a marker in, so the check is
    the real parser: a file every line of which is a task is a task file.
    """
    from wringer import fleet

    if not path.exists():
        return True
    try:
        fleet.load_tasks(path)
    except fleet.FleetError:
        return False
    return True


def brief_is_generated(path: Path) -> bool:
    return _carries(path, BRIEF_MARKER)


def rubric_is_generated(path: Path) -> bool:
    """A committed, hand-written rubric is not ours to replace.

    `judge.rubric:` has pointed at a file since v0.2, so a repo adopting
    `wring spec` may already have one — and it is the document that decides
    whether work is accepted.
    """
    return _carries(path, RUBRIC_MARKER)


def _carries(path: Path, marker: str) -> bool:
    if not path.exists():
        return True
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:300]
    except OSError:
        return False
    return marker in head


# --- the drafting bundle -------------------------------------------------


@dataclass(frozen=True)
class Bundle:
    """`.wringer/specs/<id>/`. Owns the redactor, so every write scrubs.

    The judge's shape, for the judge's reason: what would leave the machine is
    on disk before any socket opens, so it is auditable rather than asserted.
    """

    directory: Path
    spec_id: str
    started_at: datetime
    redactor: Redactor = Redactor()

    @classmethod
    def create(
        cls,
        specs_root: Path,
        now: datetime | None = None,
        redactor: Redactor | None = None,
    ) -> Bundle:
        started_at = now if now is not None else datetime.now().astimezone()
        try:
            specs_root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise SpecError(f"cannot create {specs_root}: {exc}") from exc
        for _ in range(64):
            spec_id = evidence.new_run_id(started_at)
            directory = specs_root / spec_id
            try:
                directory.mkdir(exist_ok=False)
            except FileExistsError:
                continue
            except OSError as exc:
                raise SpecError(f"cannot create {directory}: {exc}") from exc
            return cls(directory, spec_id, started_at, redactor or Redactor())
        raise SpecError(f"could not allocate a directory under {specs_root}")

    def write_request(self, request: dict) -> Path:
        path = self.directory / REQUEST_FILENAME
        scrubbed = evidence.deep_scrub(self.redactor, request)
        path.write_text(json.dumps(scrubbed, indent=2) + "\n", encoding="utf-8")
        return path

    def write_response(self, body: Any) -> Path:
        path = self.directory / RESPONSE_FILENAME
        scrubbed = evidence.deep_scrub(self.redactor, body)
        path.write_text(json.dumps(scrubbed, indent=2) + "\n", encoding="utf-8")
        return path

    def write_summary(
        self, mode: str, prd: str, endpoint: str, model: str, drafted: Spec | None
    ) -> Path:
        lines = [
            f"# wring spec — {self.spec_id}",
            "",
            f"- mode: **{mode}**",
            f"- PRD: `{prd}`",
            f"- endpoint: `{self.redactor.scrub(endpoint)}`",
            f"- model: {model}",
        ]
        if drafted is None and mode == "dry_run":
            lines += [
                "",
                "Nothing was drafted: this was a dry run, so the request was "
                f"built and written to `{REQUEST_FILENAME}` and no socket was "
                "opened.",
            ]
        elif drafted is None:
            # A live run that produced nothing is NOT a dry run, and a summary
            # that said so would be a false claim in an evidence artifact.
            lines += [
                "",
                "**Nothing was drafted, and no spec file was written.** The "
                "request was sent and the exchange did not produce a usable "
                f"`{SCHEMA_VERSION}` document — see `{REQUEST_FILENAME}` and, "
                f"if a reply arrived at all, `{RESPONSE_FILENAME}`. The error "
                "is on the console.",
            ]
        else:
            lines += [
                f"- drafted: `{SPEC_FILENAME}` — **approved: false**",
                "",
                f"| {len(drafted.criteria)} criteria "
                f"| {len(drafted.gates)} gates "
                f"| {len(drafted.tasks)} tasks "
                f"| {len(drafted.questions)} open questions |",
                "|---|---|---|---|",
                "",
                f"Read `{SPEC_FILENAME}`, answer its open questions, and set "
                "`approved: true` by hand. Then run `wring plan`.",
            ]
        path = self.directory / SUMMARY_FILENAME
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return path
