def _scalar(value: str) -> str:
    """One YAML scalar, on exactly one line, holding exactly `value`.

    A JSON string is a YAML double-quoted scalar, so `json.dumps` is the
    emitter: it quotes unconditionally, escapes every C0 control character,
    and — the property this needs — can never emit a line break. This renderer
    builds the file line by line, and a scalar that decided to span three of
    them would land at an indentation nobody chose.

    The two escapes JSON does not make are added by hand: U+2028 and U+2029
    are ordinary characters to JSON and **line breaks to YAML**. `\\x85` is
    the same story.

    Nothing is stripped. An earlier version trimmed the emitter's trailing
    document marker with `.strip()`, which also ate any leading or trailing
    Unicode whitespace in the value itself — so a title ending in a non-
    breaking space was quietly written down as a different title.
    """
    dumped = json.dumps(value, ensure_ascii=False)
    for char in ("\x85", " ", " "):
        dumped = dumped.replace(char, f"\\u{ord(char):04x}")

    # The file is meant to be read, and quoting every scalar is noise. So try
    # the plain form — and *check* it, rather than assuming which cases are
    # safe. If it does not read back byte-identical on one line, the quoted
    # form stands. A prettifier that guesses is how the last bug got in.
    plain = (
        yaml.safe_dump(value, default_flow_style=True, allow_unicode=True,
                       width=10**6)
        .removesuffix("\n...\n")
        .removesuffix("\n")
    )
    if plain and "\n" not in plain:
        try:
            if yaml.safe_load(f"k: {plain}")["k"] == value:
                return plain
        except (yaml.YAMLError, KeyError, TypeError):
            pass
    return dumped


