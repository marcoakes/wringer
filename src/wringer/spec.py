class SpecError(Exception):
    """An unusable spec, PRD or reply (CLI exit code 2)."""


@dataclass(frozen=True)
class Question:
    id: str
    question: str
    required: bool = True
    answer: str = ""

    @property
    def answered(self) -> bool:
        """A question is answered when someone wrote an answer under it.

        Deleting the question works too — it is simply gone. Both are file
        edits, which is the only kind of approval this slice accepts.
        """
        return bool(self.answer.strip())


@dataclass(frozen=True)
class Task:
    id: str
    brief: str
    objective: str
    dir: str = "."


@dataclass(frozen=True)
class Assumption:
    """A decision the drafter took INSTEAD of asking, and the question it
    displaced (SPEC_PMPLAN_V0 ruling 1).

    `instead_of_asking` is what keeps this channel from becoming the thing it
    replaces. An assumption is a question somebody chose not to ask; carrying
    that question means the person is always ONE ACTION away from asking it
    after all. Without it, `assumptions:` would be a tidier place to hide a
    decision than `guidance` was.

    Its `id` obeys the frozen question-id rule byte for byte, because
    `wringer-board revise` promotes an assumption INTO `open_questions` — an id
    this parser accepted and `_parse_questions` would not is a spec the
    engine's own loader then refuses, leaving a person a broken file and an
    error about a document they never hand-edited.
    """

    id: str
    decision: str
    why: str
    instead_of_asking: str
    # **The criteria this decision SHAPED** — `wringer.decisions.v2`, added
    # 2026-08-21. Only the drafter can know these: it took the decision and
    # then wrote the criteria in the same reply. Without them, overruling an
    # assumption leaves every criterion derived from it standing against the
    # person, which is the inconsistency Wringer manufactured on a real run.
    #
    # Empty is NOT evidence that none exist — an older sidecar has none and a
    # drafter may simply not emit them. The heuristic note downstream says so
    # in those words.
    criteria: tuple[str, ...] = ()


@dataclass(frozen=True)
class Draft:
    """What one drafting reply yielded: the spec, and the gates it proposed.

    Two documents rather than one field on `Spec`, because `Spec` maps to a
    frozen schema and a proposed binding has no home in it. Returned together
    so a caller cannot write the spec and forget the sidecar, or write a
    sidecar whose bindings were never checked against the criteria beside it.
    """

    spec: Spec
    gates: tuple[config.Gate, ...] = ()
    # Decisions taken instead of asking — the third document, and the same
    # reasoning as `gates`: no home in the frozen spec, and meaningless apart
    # from the criteria it was drafted beside.
    assumptions: tuple[Assumption, ...] = ()
    # One plain sentence per task id: what the PERSON will be able to do when
    # it is done, beside the machine `objective` the engineer works from. Same
    # sidecar, same reason — `spec.schema.json`'s task items are frozen and
    # closed, so this cannot be a fourth key on a task.
    outcomes: dict[str, str] = field(default_factory=dict)
    # Bindings the reply proposed and this parser REFUSED, each with the
    # reason, for the caller to put in front of whoever ran the command. Not
    # an exception: one unusable binding is not a reason to throw away a whole
    # drafted spec, and a criterion with no binding is already a legal state
    # the plan renders in words ("NOTHING CHECKS THIS YET").
    notes: tuple[str, ...] = ()


@dataclass(frozen=True)
class Spec:
    approved: bool
    title: str
    intent: str
    questions: tuple[Question, ...]
    criteria: tuple[Criterion, ...]
    gates: tuple[config.Gate, ...]
    tasks: tuple[Task, ...]
    path: str

    @property
    def unanswered(self) -> tuple[Question, ...]:
        return tuple(q for q in self.questions if q.required and not q.answered)


